@router.get("/projects/{project_id}/materials")
async def get_customer_materials(
    project_id: str,
    current_user: Dict[str, Any] = Depends(require_role([UserRole.CUSTOMER.value]))
):
    """Get material estimation breakdown generated by the Architect."""
    await check_project_access(current_user, project_id)
    db = get_db()
    estimate = await db[PROJECT_ESTIMATES_COLLECTION].find_one({"project_id": project_id}, {"_id": 0})
    if not estimate:
        return {"project_id": project_id, "materials": {}, "message": "No material estimation on record yet"}

    # Extract user-friendly material quantities
    quantities = estimate.get("material_quantities") or estimate.get("predicted_quantities") or {}
    return {
        "project_id": project_id,
        "materials": quantities,
        "total_cost": estimate.get("predicted_cost_inr"),
        "breakdown": estimate.get("cost_breakdown")
    }


