from fastapi import APIRouter, Depends, HTTPException, status
from typing import Dict, Any, List
from middleware.auth import require_role, check_project_access
from models.auth import UserRole
from config import (
    get_db,
    PROJECTS_COLLECTION,
    PROJECT_ESTIMATES_COLLECTION,
    PROGRESS_UPDATES_COLLECTION,
    SITE_IMAGES_COLLECTION
)

router = APIRouter(
    prefix="/api/customer",
    tags=["Customer"],
    dependencies=[Depends(require_role([UserRole.CUSTOMER.value]))]
)


@router.get("/dashboard")
async def get_customer_dashboard(current_user: Dict[str, Any] = Depends(require_role([UserRole.CUSTOMER.value]))):
    """
    Overview dashboard for the logged-in customer showing their assigned projects,
    active construction progress, total cost, carbon, and sustainability scores.
    """
    db = get_db()
    user_id = current_user.get("user_id")
    user_email = current_user.get("email")
    assigned_ids = current_user.get("assigned_project_ids", [])

    # Find projects assigned to this customer
    query = {
        "$or": [
            {"customer_id": user_id},
            {"customer_email": user_email},
            {"project_id": {"$in": assigned_ids}}
        ]
    }
    projects = await db[PROJECTS_COLLECTION].find(query, {"_id": 0}).to_list(50)

    if not projects:
        return {
            "has_project": False,
            "message": "No construction projects currently assigned to your account",
            "projects": []
        }

    # Use primary project
    primary_project = projects[0]
    pid = primary_project.get("project_id")

    # Fetch latest calculation estimate from existing collection
    estimate = await db[PROJECT_ESTIMATES_COLLECTION].find_one(
        {"project_id": pid},
        {"_id": 0}
    )

    # Fetch site images count
    images_count = await db[SITE_IMAGES_COLLECTION].count_documents({"project_id": pid})

    # Fetch recent updates
    recent_updates = await db[PROGRESS_UPDATES_COLLECTION].find(
        {"project_id": pid},
        {"_id": 0}
    ).sort("created_at", -1).limit(5).to_list(5)

    return {
        "has_project": True,
        "customer_name": current_user.get("name"),
        "primary_project": primary_project,
        "all_projects": projects,
        "latest_estimate": estimate,
        "images_count": images_count,
        "recent_updates": recent_updates
    }


